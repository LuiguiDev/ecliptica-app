// Polo norte de la eclíptica (AR 18h, Dec +66.56°): las figuras se orientan
// con la eclíptica en horizontal, igual que el anillo de la escena.
const ECL_POLE = toVector(18, 66.56);

function toVector(raHours, decDeg) {
  const ra = (raHours * 15 * Math.PI) / 180;
  const dec = (decDeg * Math.PI) / 180;
  return [Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec)];
}

const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const normalize = a => {
  const l = Math.hypot(...a);
  return a.map(v => v / l);
};

// Proyección gnomónica (como se ve el cielo desde la Tierra) centrada en la
// constelación, normalizada a [-1, 1] conservando las proporciones.
function project(c) {
  const vecs = c.stars.map(([, ra, dec]) => toVector(ra, dec));
  const center = normalize(vecs.reduce((s, v) => s.map((x, i) => x + v[i]), [0, 0, 0]));
  const east = normalize(cross(ECL_POLE, center));
  const north = cross(center, east);
  const pts = vecs.map(v => {
    const d = dot(v, center);
    return [-dot(v, east) / d, dot(v, north) / d];
  });
  const xs = pts.map(p => p[0]);
  const ys = pts.map(p => p[1]);
  const cx = (Math.max(...xs) + Math.min(...xs)) / 2;
  const cy = (Math.max(...ys) + Math.min(...ys)) / 2;
  const half = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) / 2;
  return pts.map(([x, y]) => [(x - cx) / half, (y - cy) / half]);
}

export const STAR_TONES = { blue: '#5cb8ff', orange: '#ff9a3c' };

export const ZODIAC = CATALOG.map(c => {
  const index = Object.fromEntries(c.stars.map(([id], i) => [id, i]));
  return {
    name: c.name,
    range: c.range,
    stars: project(c),
    mags: c.stars.map(s => s[3]),
    lines: c.lines.map(([a, b]) => [index[a], index[b]]),
    featured: c.featured.map(f => ({ ...f, index: index[f.star], color: STAR_TONES[f.tone] })),
  };
});

// Día del año del equinoccio de marzo (21 de marzo ≈ día 80)
export const MARCH_EQUINOX_DAY = 80;

// Longitud eclíptica del Sol [0,360) para un día del año (1-365)
export function sunLongitude(dayOfYear) {
  return ((((dayOfYear - MARCH_EQUINOX_DAY) % 365) + 365) % 365) * (360 / 365);
}

export function signIndexForLongitude(lambda) {
  return Math.floor(((lambda % 360) + 360) % 360 / 30) % 12;
}

const MONTHS = [
  ['enero', 31], ['febrero', 28], ['marzo', 31], ['abril', 30],
  ['mayo', 31], ['junio', 30], ['julio', 31], ['agosto', 31],
  ['septiembre', 30], ['octubre', 31], ['noviembre', 30], ['diciembre', 31],
];

export function dayToDate(dayOfYear) {
  let d = dayOfYear;
  for (const [name, len] of MONTHS) {
    if (d <= len) return `${d} de ${name}`;
    d -= len;
  }
  return '31 de diciembre';
}
